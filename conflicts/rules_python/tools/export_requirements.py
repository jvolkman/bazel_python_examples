"""Exports a requirements file for pip.parse from a uv.lock.

Runs `uv export --frozen` (no re-resolution, so uv.lock stays the single source
of truth) and then puts back the extras that dependents request.

`uv export` writes a flat list such as `cuda-toolkit==13.2.2`, even when torch
asks for `cuda-toolkit[cudart,cublas,...]`. rules_python builds the dependency
graph from each wheel's METADATA and only enables the extras written on the
requirement line, so without this step `cuda-toolkit` would not depend on
`nvidia-cuda-runtime` and `import torch` fails with
`libcudart.so.13: cannot open shared object file`.

Usage (via `bazel run`, see BUILD.bazel):
  export_requirements --uv <uv> --project <dir> --output <file> [--check] -- <uv export args>
"""

import argparse
import os
import re
import subprocess
import sys
import tomllib

_REQ_LINE = re.compile(r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)==(?P<version>[^ ;\\]+)")


def _normalize(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def _requested_extras(lock, exported):
    """Maps package name -> extras requested by exported packages or roots."""
    extras = {}
    for pkg in lock["package"]:
        name = _normalize(pkg["name"])
        source = pkg.get("source", {})
        is_root = "virtual" in source or "editable" in source
        if not is_root and exported.get(name) != pkg["version"]:
            continue
        edges = list(pkg.get("dependencies", []))
        for table in ("optional-dependencies", "dev-dependencies"):
            for group in pkg.get(table, {}).values():
                edges.extend(group)
        for dep in edges:
            dep_name = _normalize(dep["name"])
            if dep.get("extra") and dep_name in exported:
                extras.setdefault(dep_name, set()).update(dep["extra"])
    return extras


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--uv", required=True)
    parser.add_argument("--project", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("export_args", nargs="*")
    args = parser.parse_args()

    workspace = os.environ.get("BUILD_WORKSPACE_DIRECTORY", "")
    project = os.path.join(workspace, args.project)
    output = os.path.join(workspace, args.output)

    exported_text = subprocess.run(
        [
            args.uv,
            "--no-config",
            "--quiet",
            "--no-cache",
            "export",
            "--project",
            project,
            "--frozen",
            "--no-header",
            "--format",
            "requirements.txt",
            *args.export_args,
        ],
        check=True,
        capture_output=True,
        text=True,
    ).stdout

    lines = exported_text.splitlines()
    exported = {}
    for line in lines:
        m = _REQ_LINE.match(line)
        if m:
            exported[_normalize(m["name"])] = m["version"]

    with open(os.path.join(project, "uv.lock"), "rb") as f:
        extras = _requested_extras(tomllib.load(f), exported)

    out = []
    for line in lines:
        m = _REQ_LINE.match(line)
        wanted = m and extras.get(_normalize(m["name"]))
        if wanted:
            line = "{}[{}]{}".format(m["name"], ",".join(sorted(wanted)), line[len(m["name"]):])
        out.append(line)
    content = "# Generated by tools/export_requirements.py from {}/uv.lock. Do not edit.\n".format(
        args.project
    ) + "\n".join(out) + "\n"

    if args.check:
        with open(output) as f:
            if f.read() != content:
                sys.exit("{} is out of date; run `bazel run {}`".format(args.output, os.environ.get("TARGET", "the .update target")))
        return
    with open(output, "w") as f:
        f.write(content)


if __name__ == "__main__":
    main()
